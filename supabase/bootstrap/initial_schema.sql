begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'clinics'
      and policyname = 'Managers and super admins can view clinics'
  ) then
    if not exists (
      select 1 from pg_policies
      where schemaname = 'public' and tablename = 'clinics'
        and policyname = 'Managers can view their clinic'
    ) then
      create policy "Managers can view their clinic"
        on public.clinics for select to authenticated
        using (exists (
          select 1 from public.clinic_members
          where clinic_members.clinic_id = clinics.id
            and clinic_members.user_id = auth.uid()
        ));
    end if;
