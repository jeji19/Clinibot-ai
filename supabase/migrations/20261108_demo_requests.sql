-- CliniBot AI: persist incoming clinic demo leads
create table if not exists public.demo_requests (
  id bigint generated by default as identity primary key,
  clinic_name text not null,
  contact_name text not null,
  email text not null,
  phone text,
  specialty text,
  status text not null default 'new' check (status in ('new','contacted','converted','closed')),
  created_at timestamptz not null default now()
);

alter table public.demo_requests enable row level security;

-- No public or clinic-manager access. Platform Super Admin reads through
-- the authenticated, server-verified endpoint using the service role key.
drop policy if exists "No direct access to demo requests" on public.demo_requests;

create index if not exists demo_requests_created_at_idx
  on public.demo_requests (created_at desc);
