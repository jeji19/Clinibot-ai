-- CliniBot AI core schema bootstrap
-- Use ONLY for a brand-new Supabase project before applying ../migrations/*.sql.
-- This file is intentionally outside supabase/migrations so it is not treated as
-- an unapplied migration in the already-connected production project.
-- The statements are safe to re-run on this project: existing tables/indexes and
-- optimized policies are preserved.

create table if not exists public.clinics (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text,
  plan text not null default 'basic'
    check (plan in ('basic', 'pro', 'premium')),
  is_active boolean not null default true,
  notification_email text,
  created_at timestamptz not null default now()
);

create unique index if not exists clinics_slug_unique
  on public.clinics (slug);

create table if not exists public.clinic_settings (
  clinic_id uuid primary key references public.clinics(id) on delete cascade,
  description text not null default '',
  services jsonb not null default '[]'::jsonb,
  opening_hours jsonb not null default '{}'::jsonb,
  default_language text not null default 'en',
  logo_url text,
  updated_at timestamptz not null default now()
);

create table if not exists public.clinic_members (
  clinic_id uuid not null references public.clinics(id),
  user_id uuid not null references auth.users(id),
  primary key (clinic_id, user_id)
);

create table if not exists public.super_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);

create table if not exists public.appointment_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  service text default '',
  preferred_date date,
  preferred_time text,
  language text,
  status text default 'new',
  clinic_id uuid default '11111111-1111-4111-8111-111111111111'::uuid,
  patient_name text,
  patient_phone text
);

alter table public.clinics enable row level security;
alter table public.clinic_settings enable row level security;
alter table public.clinic_members enable row level security;
alter table public.super_admins enable row level security;
alter table public.appointment_requests enable row level security;

