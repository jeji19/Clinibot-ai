-- Manager appointment updates remain restricted to their own clinic.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'appointment_requests'
      and policyname = 'Managers can update clinic appointments'
  ) then
    create policy "Managers can update clinic appointments"
      on public.appointment_requests for update to authenticated
      using (exists (
        select 1 from public.clinic_members
        where clinic_members.clinic_id = appointment_requests.clinic_id
          and clinic_members.user_id = auth.uid()
      ))
      with check (exists (
        select 1 from public.clinic_members
        where clinic_members.clinic_id = appointment_requests.clinic_id
          and clinic_members.user_id = auth.uid()
      ));
  end if;
end $$;

